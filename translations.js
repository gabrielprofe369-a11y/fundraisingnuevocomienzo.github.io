function setLanguage(lang) {
    const t = translations[lang];
    if (!t) return;
    
    document.getElementById('doc-title').innerText = t.docTitle;
    document.getElementById('badge').innerText = t.badge;
    document.getElementById('hero-title').innerText = t.heroTitle;
    document.getElementById('hero-subtitle').innerText = t.heroSubtitle;
    document.getElementById('story-title').innerText = t.storyTitle;
    document.getElementById('story-p1').innerText = t.storyP1;
    document.getElementById('story-p2').innerText = t.storyP2;
    document.getElementById('story-p3').innerText = t.storyP3;
    document.getElementById('research-title').innerText = t.researchTitle;
    document.getElementById('area-1-title').innerText = t.area1Title;
    document.getElementById('area-1-desc').innerText = t.area1Desc;
    document.getElementById('area-2-title').innerText = t.area2Title;
    document.getElementById('area-2-desc').innerText = t.area2Desc;
    document.getElementById('area-3-title').innerText = t.area3Title;
    document.getElementById('area-3-desc').innerText = t.area3Desc;
    document.getElementById('book-title').innerText = t.bookTitle;
    document.getElementById('book-desc').innerText = t.bookDesc;
    document.getElementById('book-btn').innerText = t.bookBtn;
    document.getElementById('donate-title').innerText = t.donateTitle;
    document.getElementById('donate-subtitle').innerText = t.donateSubtitle;
    document.getElementById('btn-paypal').innerText = t.btnPaypal;
    document.getElementById('btn-kofi').innerText = t.btnKoFi;
    document.getElementById('bank-title').innerText = t.bankTitle;
    document.getElementById('bank-label-bank').innerText = t.bankBank;
    document.getElementById('bank-label-type').innerText = t.bankType;
    document.getElementById('bank-label-num').innerText = t.bankNum;
    document.getElementById('bank-label-owner').innerText = t.bankOwner;
    document.getElementById('footer-text').innerText = t.footerText;

    ['es', 'en', 'ka'].forEach(l => {
        const btn = document.getElementById(`btn-${l}`);
        if (btn) {
            btn.className = l === lang 
                ? "px-3 py-1.5 rounded-lg border border-indigo-500 bg-indigo-600 text-white font-bold transition"
                : "px-3 py-1.5 rounded-lg border border-slate-700 bg-slate-800 text-slate-300 hover:border-slate-500 transition";
        }
    });
}
